    @Test
    void replaysPersistedBoot3OrderWithoutReapplyingBusinessEffects() throws Exception {
        // Captured from the real Boot 3.5.16 Docker baseline, not generated by the mapper under test.
        var fixture = objectMapper.readTree(getClass().getResourceAsStream("/compatibility/boot3-order.json"));
        String key = "legacy-boot3-order";
        jdbc.update("""
                INSERT INTO idempotency_records
                    (organization_id, operation, idempotency_key, request_hash, status,
                     response_body, response_status, resource_id, expires_at)
                VALUES (?, 'sales-order.create', ?, ?, 'COMPLETED', CAST(? AS jsonb), 201, ?,
                        CURRENT_TIMESTAMP + INTERVAL '1 day')
                """, ORGANIZATION, key, fixture.path("request_hash").asText(),
                fixture.path("response").toString(), UUID.fromString(fixture.path("resource_id").asText()));
        Long before = jdbc.queryForObject("SELECT count(*) FROM sales_orders", Long.class);
        var request = new CreateOrderRequest(CUSTOMER, true, List.of(new CreateOrderRequest.Line(
                CEMENT, WAREHOUSE, CEMENT_LOCATION, new BigDecimal("0.001"), null, null, null)));
        var response = orders.create(request, key, actor(SALES_USER, "SALES_ORDER_WRITE"));
        assertThat(response.id().toString()).isEqualTo(fixture.path("resource_id").asText());
        assertThat(response.lines().getFirst().orderedQuantity()).isEqualByComparingTo("0.001");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM sales_orders", Long.class)).isEqualTo(before);
    }

    @Test
    void orderToCashAndProcurementToReceiptAreIdempotentEndToEnd() throws Exception {
        ActorContext sales = actor(SALES_USER, "SALES_ORDER_WRITE", "PROCUREMENT_WRITE");
        ActorContext finance = actor(APPROVER_USER, "BILLING_WRITE", "RECONCILIATION_WRITE", "PROCUREMENT_APPROVE");
        ActorContext warehouse = actor(WAREHOUSE_USER, "WAREHOUSE_OPERATE");

        var order = orders.create(new CreateOrderRequest(CUSTOMER, false, List.of(
                new CreateOrderRequest.Line(PLYWOOD, WAREHOUSE, PLYWOOD_LOCATION, new BigDecimal("5"),
                        null, null, null))), "e2e-order", sales);
        assertThat(order.status()).isEqualTo("RESERVED");

        UUID reservationId = jdbc.queryForObject(
                "SELECT id FROM inventory_reservations WHERE order_id = ?", UUID.class, order.id());
        var shipmentRequest = new CreateShipmentRequest(List.of(
                new CreateShipmentRequest.Line(reservationId, new BigDecimal("5"))));
        var shipment = fulfillment.ship(order.id(), shipmentRequest, "e2e-shipment", warehouse);
        var shipmentReplay = fulfillment.ship(order.id(), shipmentRequest, "e2e-shipment", warehouse);
        assertThat(shipmentReplay.id()).isEqualTo(shipment.id());
        assertThat(jdbc.queryForObject("SELECT status FROM sales_orders WHERE id = ?", String.class, order.id()))
                .isEqualTo("FULFILLED");

        var invoice = billing.createInvoice(order.id(), "e2e-invoice", finance);
        var invoiceReplay = billing.createInvoice(order.id(), "e2e-invoice", finance);
        assertThat(invoiceReplay.id()).isEqualTo(invoice.id());
        assertThat(invoice.totalAmount()).isEqualByComparingTo("236.25");

        var paymentRequest = new PaymentFileRequest("synthetic-bank-e2e.csv", List.of(
                new PaymentFileRequest.Record("SYN-E2E-0001", invoice.invoiceNumber(), null,
                        invoice.totalAmount(), LocalDate.of(2026, 8, 31))));
        var imported = reconciliation.importFile(paymentRequest, "e2e-payment", finance);
        var importReplay = reconciliation.importFile(paymentRequest, "e2e-payment", finance);
        assertThat(importReplay.fileId()).isEqualTo(imported.fileId());
        assertThat(imported.matchedCount()).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT status FROM sales_orders WHERE id = ?", String.class, order.id()))
                .isEqualTo("SETTLED");
        assertThat(jdbc.queryForObject("SELECT credit_used FROM credit_accounts WHERE customer_id = ?",
                BigDecimal.class, CUSTOMER)).isZero();

        var shortOrder = orders.create(new CreateOrderRequest(CUSTOMER, true, List.of(
                new CreateOrderRequest.Line(CEMENT, WAREHOUSE, CEMENT_LOCATION, new BigDecimal("1100"),
                        null, null, null))), "e2e-backorder", sales);
        assertThat(shortOrder.status()).isEqualTo("PARTIALLY_ALLOCATED");
        UUID suggestionId = jdbc.queryForObject(
                "SELECT id FROM procurement_suggestions WHERE order_id = ? AND status = 'OPEN'",
                UUID.class, shortOrder.id());

        var purchaseRequest = new CreatePurchaseRequest(SUPPLIER, List.of(
                new CreatePurchaseRequest.Line(suggestionId, CEMENT_LOCATION,
                        new BigDecimal("100"), new BigDecimal("8.50"))));
        var requested = procurement.create(purchaseRequest, "e2e-purchase-request", sales);
        var approved = procurement.approve(requested.id(), "e2e-purchase-approval", finance);
        UUID purchaseOrderLineId = jdbc.queryForObject(
                "SELECT id FROM purchase_order_lines WHERE purchase_order_id = ?",
                UUID.class, approved.purchaseOrderId());
        var receiptRequest = new ReceivePurchaseOrderRequest(List.of(
                new ReceivePurchaseOrderRequest.Line(purchaseOrderLineId, new BigDecimal("100"))));
        var receipt = procurement.receive(approved.purchaseOrderId(), receiptRequest, "e2e-receipt", warehouse);
        var receiptReplay = procurement.receive(approved.purchaseOrderId(), receiptRequest, "e2e-receipt", warehouse);

        assertThat(receiptReplay.status()).isEqualTo(receipt.status());
        assertThat(receipt.status()).isEqualTo("RECEIVED");
        var inventory = jdbc.queryForMap("""
                SELECT on_hand, reserved, available FROM inventory_balances
                 WHERE organization_id = ? AND warehouse_id = ? AND material_id = ? AND location_id = ?
                """, ORGANIZATION, WAREHOUSE, CEMENT, CEMENT_LOCATION);
        assertThat((BigDecimal) inventory.get("on_hand")).isEqualByComparingTo("1100");
        assertThat((BigDecimal) inventory.get("reserved")).isEqualByComparingTo("1000");
        assertThat((BigDecimal) inventory.get("available")).isEqualByComparingTo("100");

        String receiptEvent = jdbc.queryForObject("""
                SELECT payload::text FROM outbox_events
                 WHERE event_type = 'InventoryReceived' AND aggregate_id = ?
                """, String.class, approved.purchaseOrderId());
        var transaction = new TransactionTemplate(transactionManager);
        var counter = meters.counter("event_processed_total", "consumer", "erp-core-backorder-reallocation-v1");
        double processedBefore = counter.count();
        long outboxBefore = jdbc.queryForObject("SELECT count(*) FROM outbox_events", Long.class);
        long ledgerBefore = jdbc.queryForObject("SELECT count(*) FROM inventory_ledger", Long.class);
        // Inject failure after real side effects, before commit: Inbox, allocation, audit/outbox must roll back together.
        assertThatThrownBy(() -> transaction.executeWithoutResult(status -> {
            assertThat(inbox.consume(receiptEvent).reallocatedLines()).isEqualTo(1);
            throw new IllegalStateException("injected consumer failure before DB commit");
        })).isInstanceOf(IllegalStateException.class).hasMessage("injected consumer failure before DB commit");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM consumer_inbox", Long.class)).isZero();
        assertThat(jdbc.queryForObject("SELECT count(*) FROM outbox_events", Long.class)).isEqualTo(outboxBefore);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM inventory_ledger", Long.class)).isEqualTo(ledgerBefore);
        assertThat(counter.count()).isEqualTo(processedBefore);
        assertThat(jdbc.queryForObject("SELECT reserved FROM inventory_balances WHERE material_id = ?",
                BigDecimal.class, CEMENT)).isEqualByComparingTo("1000");

        var start = new CountDownLatch(1);
        List<DomainEventInboxApplicationService.ProcessingResult> results = new ArrayList<>();
        try (var executor = Executors.newVirtualThreadPerTaskExecutor()) {
            List<Future<DomainEventInboxApplicationService.ProcessingResult>> tasks = new ArrayList<>();
            for (int index = 0; index < 12; index++) tasks.add(executor.submit(() -> {
                start.await();
                return inbox.consume(receiptEvent);
            }));
            start.countDown();
            for (var task : tasks) results.add(task.get(15, TimeUnit.SECONDS));
        }
        assertThat(results.stream().filter(result -> !result.duplicate()).toList()).hasSize(1);
        assertThat(results.stream().filter(DomainEventInboxApplicationService.ProcessingResult::duplicate).toList())
                .hasSize(11);
        var processed = results.stream().filter(result -> !result.duplicate()).findFirst().orElseThrow();
        // Repeat after a successful database commit, as offset redelivery would. No Kafka offset crash is claimed here.
        var duplicate = inbox.consume(receiptEvent);
        assertThat(processed.reallocatedLines()).isEqualTo(1);
        assertThat(duplicate.duplicate()).isTrue();
        assertThat(counter.count()).isEqualTo(processedBefore + 1);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM inventory_ledger", Long.class)).isEqualTo(ledgerBefore + 1);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM outbox_events", Long.class)).isEqualTo(outboxBefore + 1);
        var reallocatedInventory = jdbc.queryForMap("""
                SELECT on_hand, reserved, available FROM inventory_balances
                 WHERE organization_id = ? AND warehouse_id = ? AND material_id = ? AND location_id = ?
                """, ORGANIZATION, WAREHOUSE, CEMENT, CEMENT_LOCATION);
        assertThat((BigDecimal) reallocatedInventory.get("reserved")).isEqualByComparingTo("1100");
        assertThat((BigDecimal) reallocatedInventory.get("available")).isZero();
        assertThat(jdbc.queryForObject("SELECT status FROM sales_orders WHERE id = ?",
                String.class, shortOrder.id())).isEqualTo("RESERVED");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM consumer_inbox WHERE event_id = ?",
                Long.class, processed.eventId())).isEqualTo(1L);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM shipment_lines WHERE shipment_id = ?",
                Long.class, shipment.id())).isEqualTo(1L);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM invoice_lines WHERE invoice_id = ?",
                Long.class, invoice.id())).isEqualTo(1L);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM payment_allocations WHERE invoice_id = ?",
                Long.class, invoice.id())).isEqualTo(1L);
    }

    private ActorContext actor(UUID userId, String... roles) {
        return new ActorContext(userId, ORGANIZATION, Set.of(roles), Set.of(WAREHOUSE));
    }
